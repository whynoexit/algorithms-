#include <bits/stdc++.h>
using namespace std;

int main() {
    // Обычный массив.
    // Размер фиксирован и известен заранее.
    int a[5] = {1, 2, 3, 4, 5};

    cout << a[0] << '\n';

    // vector — динамический массив.
    // В олимпиадах используется очень часто.
    vector<int> v = {1, 2, 3};

    // Добавить элемент в конец.
    v.push_back(4);

    // Удалить последний элемент.
    v.pop_back();

    // Размер vector.
    int n = v.size();

    // Изменить размер.
    v.resize(10);

    // Первый и последний элементы.
    cout << v.front() << '\n';
    cout << v.back() << '\n';

    // Очистить vector.
    v.clear();

    // После clear размер становится 0.
    cout << v.size() << '\n';

    // Обычный проход по индексам.
    for (int i = 0; i < (int)a.size(); i++) {
        cout << a[i] << ' ';
    }

    cout << '\n';

    // Но для обычного массива такой вариант
    // с .size() не работает.
    // Поэтому выше лучше использовать известный размер.

    vector<int> b = {10, 20, 30, 40};

    // Range-based for.
    // Когда индекс не нужен, это обычно самый простой вариант.
    for (int x : b) {
        cout << x << ' ';
    }

    cout << '\n';

    // Двумерный vector.
    vector<vector<int>> matrix(3, vector<int>(4));

    matrix[1][2] = 10;

    cout << matrix[1][2] << '\n';

    return 0;
}


