#include <bits/stdc++.h>
using namespace std;

int main() {
    // =========================
    // set
    // =========================

    // Хранит уникальные элементы в отсортированном виде.
    set<int> s;

    s.insert(5);
    s.insert(2);
    s.insert(5); // второй 5 не добавится

    // Проверяем наличие элемента.
    if (s.find(2) != s.end()) {
        cout << "2 exists\n";
    }

    // Удаляем элемент.
    s.erase(2);

    // =========================
    // multiset
    // =========================

    // В отличие от set, разрешает одинаковые элементы.
    multiset<int> ms;

    ms.insert(5);
    ms.insert(5);
    ms.insert(2);

    // count показывает, сколько раз элемент встречается.
    cout << ms.count(5) << '\n';

    // =========================
    // map
    // =========================

    // Хранит пары:
    // ключ -> значение.
    map<string, int> mp;

    mp["apple"] = 3;
    mp["banana"] = 5;

    cout << mp["apple"] << '\n';

    // Очень частое применение map —
    // подсчёт количества появлений.
    map<int, int> cnt;

    cnt[10]++;
    cnt[10]++;
    cnt[20]++;

    // =========================
    // unordered_map
    // =========================

    // Похож на map, но элементы не хранятся отсортированными.
    // Часто используется, когда порядок ключей не нужен.
    unordered_map<int, int> freq;

    freq[5]++;
    freq[5]++;
    freq[10]++;

    // =========================
    // stack
    // =========================

    // Последний добавленный элемент выходит первым.
    stack<int> st;

    st.push(10);
    st.push(20);

    cout << st.top() << '\n';

    st.pop();

    // =========================
    // queue
    // =========================

    // Первый добавленный элемент выходит первым.
    queue<int> q;

    q.push(10);
    q.push(20);

    cout << q.front() << '\n';

    q.pop();

    // =========================
    // deque
    // =========================

    // Можно добавлять и удалять элементы
    // с обоих концов.
    deque<int> dq;

    dq.push_back(10);
    dq.push_front(20);

    cout << dq.front() << ' ' << dq.back() << '\n';

    // =========================
    // priority_queue
    // =========================

    // По умолчанию первым отдаёт максимальный элемент.
    priority_queue<int> pq;

    pq.push(3);
    pq.push(10);
    pq.push(5);

    cout << pq.top() << '\n'; // 10

    // Если нужен минимум:
    priority_queue<int, vector<int>, greater<int>> min_pq;

    min_pq.push(3);
    min_pq.push(10);
    min_pq.push(5);

    cout << min_pq.top() << '\n'; // 3

    return 0;
}