#include <bits/stdc++.h>
using namespace std;

int main() {
    // =========================
    // auto
    // =========================

    // Компилятор сам определяет тип переменной.
    auto x = 10;
    auto name = string("Alex");

    // Особенно удобно использовать auto с итераторами.
    vector<int> a = {1, 2, 3};

    auto it = a.begin();

    cout << *it << '\n';

    // =========================
    // const
    // =========================

    // Значение нельзя изменить после создания.
    const int MAX_N = 1000;

    // const часто используется при передаче
    // больших объектов в функцию.
    // Это означает:
    // "функция может читать объект,
    // но не может его изменить".
    const vector<int> b = {1, 2, 3};

    // =========================
    // Ссылка &
    // =========================

    int value = 10;

    // ref — другое имя для value.
    int& ref = value;

    ref = 20;

    cout << value << '\n'; // 20

    // =========================
    // Lambda
    // =========================

    // Lambda — маленькая функция прямо внутри кода.
    auto square = [](int x) {
        return x * x;
    };

    cout << square(5) << '\n';

    // Особенно полезна lambda,
    // когда нужно передать собственное правило
    // в стандартный алгоритм.
    sort(a.begin(), a.end(), [](int x, int y) {
        return x > y;
    });

    // Теперь a отсортирован по убыванию.

    // =========================
    // using
    // =========================

    // Можно дать типу короткое имя.
    using ll = long long;

    ll big_number = 1000000000000LL;

    cout << big_number << '\n';

    // =========================
    // static_cast
    // =========================

    int p = 5;
    int q = 2;

    // Без приведения получится целочисленное деление.
    cout << p / q << '\n';

    // Если нужен результат 2.5:
    cout << static_cast<double>(p) / q << '\n';

    // =========================
    // array
    // =========================

    // std::array похож на обычный массив,
    // но ведёт себя как STL-контейнер.
    array<int, 3> arr = {1, 2, 3};

    cout << arr.size() << '\n';

    // =========================
    // bitset
    // =========================

    // Хранит фиксированное количество битов.
    bitset<8> bits;

    bits[0] = 1;
    bits[3] = 1;

    cout << bits << '\n';

    // =========================
    // numeric_limits
    // =========================

    cout << numeric_limits<int>::max() << '\n';
    cout << numeric_limits<int>::min() << '\n';

    return 0;
}